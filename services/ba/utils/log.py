"""Custom request-scoped logging utility for the Karofi B2B Sales Agent.

Supports JSON formatting for production integration and colorful, human-readable
text formatting for local development, alongside per-request log trace capturing.
"""

import logging as std_logging

# Silence noisy OpenTelemetry context detach warnings (caused by GeneratorExit inside async generators)
std_logging.getLogger("opentelemetry.context").setLevel(std_logging.CRITICAL)

import json
import time
from contextvars import ContextVar
from datetime import datetime

from config.base_config import settings

# Per-request log buffer for capturing pipeline traces
_log_buffer: ContextVar[list[str] | None] = ContextVar("_log_buffer", default=None)


class logging:
    """Custom logging class to handle different log levels.

    Supports two output formats controlled by LOG_FORMAT env var:
    - "json"  → single-line JSON per entry (VictoriaLogs / production)
    - "text"  → colorful plain text (default, local dev)

    Pipeline trace capture:
    - Call ``start_capture()`` at the beginning of a request
    - All log calls will append formatted text to a ContextVar buffer
    - Call ``flush_capture()`` at the end to retrieve the full trace string
    """

    RESET = "\033[0m"
    COLORS = {  # noqa: RUF012
        "DEBUG": "\033[36m",  # Cyan
        "INFO": "\033[32m",  # Green
        "WARNING": "\033[33m",  # Yellow
        "ERROR": "\033[31m",  # Red
        "USER": "\033[94m",  # Blue
        "AGENT": "\033[92m",  # Green
        "TOOL": "\033[93m",  # Yellow
    }

    def __init__(self):
        """Initialize the logger with level and format settings."""
        self.loglevel = settings.log_level.upper()
        self.json_mode = getattr(settings, "log_format", "text").lower() == "json"

    # ── Capture helpers ──────────────────────────────────────

    @staticmethod
    def start_capture() -> None:
        """Begin capturing log output for the current request context."""
        _log_buffer.set([])

    @staticmethod
    def flush_capture() -> str:
        """Return accumulated log text and reset the buffer.

        ## Returns:
            The joined string of all captured logs, or an empty string if no logs were captured.
        """
        buf = _log_buffer.get(None)
        _log_buffer.set(None)
        if not buf:
            return ""
        return "\n".join(buf)

    @staticmethod
    def _append(line: str) -> None:
        """Append a plain-text line to the capture buffer if capture is active.

        ## Args:
            line: The log message to append.
        """
        buf = _log_buffer.get(None)
        if buf is not None:
            buf.append(line)

    # ── Core log method ──────────────────────────────────────

    def log(self, level: str, message: str):
        """Log a message at the specified severity level.

        ## Args:
            level: The log severity level (e.g., 'INFO', 'DEBUG', 'WARNING', 'ERROR').
            message: The message to print and/or capture.
        """
        timestamp = time.strftime("%Y-%m-%d %H:%M:%S")

        # Always append to capture buffer (strip ANSI)
        self._append(f"[{timestamp}] {level}: {message}")

        if self.json_mode:
            # ── JSON mode: single line, VictoriaLogs-compatible ──
            entry = {
                "_msg": message,
                "level": level.lower(),
                "ts": datetime.utcnow().isoformat(timespec="milliseconds") + "Z",
            }
            print(json.dumps(entry, ensure_ascii=False), flush=True)
        else:
            # ── Text mode: colorful, human-readable ──
            color = self.COLORS.get(level, "")
            reset = self.RESET
            print(f"{color}[{level}] - {timestamp}{reset} - {message}", flush=True)

    def agent(self, content: str, end: str = "\n"):
        """Log an agent response message.

        ## Args:
            content: The text content generated by the agent.
            end: The end character of the print output.
        """
        timestamp = datetime.now().strftime("%H:%M:%S")
        self._append(f"[{timestamp}] AGENT: {content}")

        if self.json_mode:
            entry = {
                "_msg": content,
                "level": "agent",
                "ts": datetime.utcnow().isoformat(timespec="milliseconds") + "Z",
            }
            print(json.dumps(entry, ensure_ascii=False), flush=True)
        else:
            color = self.COLORS.get("AGENT", "")
            reset = self.RESET
            print(f"{color}[{timestamp}] AGENT:{reset} {content}", end=end, flush=True)

    def user(self, content: str, end: str = "\n"):
        """Log a user input message.

        ## Args:
            content: The text content received from the user.
            end: The end character of the print output.
        """
        timestamp = datetime.now().strftime("%H:%M:%S")
        self._append(f"[{timestamp}] USER: {content}")

        if self.json_mode:
            entry = {
                "_msg": content,
                "level": "user",
                "ts": datetime.utcnow().isoformat(timespec="milliseconds") + "Z",
            }
            print(json.dumps(entry, ensure_ascii=False), flush=True)
        else:
            color = self.COLORS.get("USER", "")
            reset = self.RESET
            print(f"{color}[{timestamp}] USER:{reset} {content}", end=end, flush=True)

    def tool(self, content: str, end: str = "\n"):
        """Log a tool execution message.

        ## Args:
            content: The description or payload of the tool execution.
            end: The end character of the print output.
        """
        timestamp = datetime.now().strftime("%H:%M:%S")
        self._append(f"[{timestamp}] TOOL: {content}")

        if self.json_mode:
            entry = {
                "_msg": content,
                "level": "tool",
                "ts": datetime.utcnow().isoformat(timespec="milliseconds") + "Z",
            }
            print(json.dumps(entry, ensure_ascii=False), flush=True)
        else:
            color = self.COLORS.get("TOOL", "")
            reset = self.RESET
            print(f"{color}[{timestamp}] TOOL:{reset} {content}", end=end, flush=True)

    def debug(self, message: str):
        """Log a debug-level message if logging level is DEBUG.

        ## Args:
            message: The debug message to log.
        """
        if self.loglevel == "DEBUG":
            self.log("DEBUG", message)

    def info(self, message: str):
        """Log an info-level message.

        ## Args:
            message: The informational message to log.
        """
        if self.loglevel in ["DEBUG", "INFO"]:
            self.log("INFO", message)

    def warning(self, message: str):
        """Log a warning-level message.

        ## Args:
            message: The warning message to log.
        """
        if self.loglevel in ["DEBUG", "INFO", "WARNING"]:
            self.log("WARNING", message)

    def error(self, message: str):
        """Log an error-level message.

        ## Args:
            message: The error message to log.
        """
        if self.loglevel in ["DEBUG", "INFO", "ERROR", "WARNING"]:
            self.log("ERROR", message)


if __name__ == "__main__":
    pass
